def expand_abbreviation(abbr: str) -> list[str]:
    """Return known full forms for *abbr*, or [] if unknown."""
    return ABBREVIATIONS.get(abbr.strip().upper(), [])


def get_concept_synonyms(category: str) -> frozenset[str]:
    """
    Return all known synonyms for any NCIt-backed category.

    Covers endpoints, response criteria, diseases, drugs, drug targets,
    AE types, lab tests, and statistical methods — every category defined
    in tools/build_endpoint_ontology.py.

    Returns frozenset() when the category is unknown or the JSON is absent.
    """
    return ENDPOINT_SYNONYMS.get(category, frozenset())

# Backward-compatible alias
get_endpoint_synonyms = get_concept_synonyms


def get_drug_synonyms(name: str) -> list[str]:
    """Return known aliases/codes for a drug name (case-insensitive), or []."""
    return DRUG_SYNONYMS.get(name.strip().lower(), [])


def get_disease_synonyms(name: str) -> list[str]:
    """Return known variants for a disease name (case-insensitive), or []."""
    return DISEASE_SYNONYMS.get(name.strip().lower(), [])


def get_role_synonyms(role: str) -> list[str]:
    """Return curated synonyms for *role* (case-insensitive), or []."""
    return ROLE_SYNONYMS.get(role.strip().lower(), [])


def build_regex_patterns(text: str) -> list[str]:
    """
    Build a list of regex patterns covering the CI text and its known
    abbreviation / parenthetical variants.

    Patterns are returned de-duplicated and ready for ``re.search``.
    """
    patterns: list[str] = []

    # 1. Literal match of the raw text (re-escaped)
    patterns.append(re.escape(text))

    # 2. If the text IS an abbreviation, add its expansions
    for exp in expand_abbreviation(text.strip()):
        patterns.append(re.escape(exp))

    # 3. Drug synonyms (generic name or alias appears in text)
    for syns in [get_drug_synonyms(text), get_disease_synonyms(text)]:
        for s in syns:
            patterns.append(re.escape(s))

    # 4. Abbreviations embedded inside parentheses: "Overall Response Rate (ORR)"
    for abbr in re.findall(r"\(([A-Z][A-Z0-9-]+)\)", text):
        patterns.append(r"\b" + re.escape(abbr) + r"\b")
        for exp in expand_abbreviation(abbr):
            patterns.append(re.escape(exp))

    # Deduplicate while preserving order
    seen: set[str] = set()
    unique: list[str] = []
    for p in patterns:
        if p not in seen:
            seen.add(p)
            unique.append(p)
    return unique
