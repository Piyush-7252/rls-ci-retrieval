logger = logging.getLogger(__name__)

# ─────────────────────────────────────────────────────────────────────────────
# Endpoint synonym table — loaded from shared/data/endpoint_concepts.json
# ─────────────────────────────────────────────────────────────────────────────
# {category_label: frozenset[synonym_str]}  e.g. {"orr": frozenset({...}), ...}
#
# ENDPOINT_SYNONYMS is the single source of truth for endpoint term matching
# across the entire pipeline.  Components query it via get_endpoint_synonyms().
#
# Populated at module init; falls back to {} (sub-intent matching disabled)
# when the JSON is absent so no component crashes.

def _load_clinical_concepts_json() -> tuple[dict[str, frozenset[str]], dict[str, dict]]:
    """
    Locate and load shared/data/clinical_concepts.json.

    Resolution order (stops at first hit):
      1. shared/data/clinical_concepts.json   — canonical, written by build tool
      2. reranker/data/clinical_concepts.json — mirror for Lambda packages
      3. shared/data/endpoint_concepts.json   — legacy name (backward compat)
      4. reranker/data/endpoint_concepts.json — legacy mirror

    OS guard: the bare "os" token is space-padded to " os " to prevent
    substring collision with "those", "dose", "close", etc.

    Returns:
      (categories, metadata)
      categories : {category_name: frozenset[synonym_str]}
      metadata   : {category_name: {"group": str, "canonical_name": str}}
    Both dicts are empty on failure — no component crashes.
    """
    base = Path(__file__).parent
    reranker_base = base.parent / "lambdas" / "search" / "reranker" / "data"
    candidates = [
        base / "data" / "clinical_concepts.json",
        reranker_base / "clinical_concepts.json",
        base / "data" / "endpoint_concepts.json",    # legacy
        reranker_base / "endpoint_concepts.json",    # legacy
    ]
    for path in candidates:
        if not path.exists():
            continue
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            raw: dict[str, list[str]] = data.get("categories", {})
            if not raw:
                continue
            meta: dict[str, dict] = data.get("metadata", {})
            result: dict[str, frozenset[str]] = {}
            for cat, syns in raw.items():
                kws: set[str] = set()
                for s in syns:
                    kws.add(" os " if (cat == "os" and s.strip() == "os") else s)
                result[cat] = frozenset(kws)
            total = sum(len(v) for v in result.values())
            logger.info(
                "[clinical_ontology] %s loaded: %d synonyms across %d categories (built %s)",
                path.name, total, len(result), data.get("built_at", "?"),
            )
            return result, meta
        except Exception as exc:
            logger.warning("[clinical_ontology] %s unreadable: %s", path, exc)

    logger.warning(
        "[clinical_ontology] clinical_concepts.json not found — "
        "synonym matching falls back to hardcoded ABBREVIATIONS entries.  "
        "Run tools/build_endpoint_ontology.py to generate it."
    )
    return {}, {}


# All NCIt-backed synonyms, indexed by category name.
# Covers: endpoints, response criteria, diseases, drugs, targets, AE types,
#         lab tests, statistical methods, clinical trial roles.
ENDPOINT_SYNONYMS: dict[str, frozenset[str]]
_CONCEPT_METADATA: dict[str, dict]
ENDPOINT_SYNONYMS, _CONCEPT_METADATA = _load_clinical_concepts_json()

# ─────────────────────────────────────────────────────────────────────────────
# Helpers to pull NCIt synonyms into structured vocabulary dicts
# ─────────────────────────────────────────────────────────────────────────────

def _ncit_synonyms(category: str, fallback: list[str]) -> list[str]:
    """
    Return NCIt-backed synonyms for *category* as a sorted list.

    Short all-uppercase tokens (≤5 chars) are excluded from the returned list
    because they belong as keys in ABBREVIATIONS, not as expansion values.
    Falls back to *fallback* when the JSON is absent or the category is empty.
    """
    syns = ENDPOINT_SYNONYMS.get(category, frozenset())
    cleaned = sorted(s for s in syns if not (len(s) <= 5 and s == s.upper()))
    return cleaned if cleaned else fallback

# Keep _endpoint_expansions as an alias for backward compatibility
_endpoint_expansions = _ncit_synonyms


def _auto_populate(prefix: str) -> dict[str, list[str]]:
    """
    Build a vocabulary dict from every category whose name starts with *prefix*.

    Key  = category’s canonical_name from build-tool metadata (e.g. "daratumumab"),
           or the bare suffix after *prefix* when canonical_name is absent.
    Value = all synonyms for that category, sorted.

    This means adding a new drug/disease/role to tools/build_endpoint_ontology.py
    and re-running the build is the ONLY step needed — zero changes here.
    """
    out: dict[str, list[str]] = {}
    for cat, syns in ENDPOINT_SYNONYMS.items():
        if cat.startswith(prefix):
            canonical = (
                _CONCEPT_METADATA.get(cat, {}).get("canonical_name")
                or cat[len(prefix):]
            )
            out[canonical] = sorted(syns)
    return out

