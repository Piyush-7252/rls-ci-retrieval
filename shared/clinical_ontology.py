"""
Controlled Clinical Vocabulary
================================
Source-of-truth for abbreviation expansion, synonym resolution, and regex
pattern generation used by EVERY component in the pipeline:
  • clinical_dict.py    — fast dictionary NER pre-pass
  • query_normalizer    — CI text expansion before retrieval
  • aggregator          — contradiction scoring
  • reranker            — entity overlap, intent alignment, sub-intent classification

Endpoint term knowledge (ORR synonyms, PFS synonyms, …) is loaded at module
init from shared/data/endpoint_concepts.json — generated by
tools/build_endpoint_ontology.py using NCI Thesaurus concept IDs.  This makes
every component consistent: if the JSON says "durable response rate" is an ORR
synonym, it is treated that way everywhere, not just in the reranker.

Non-endpoint entries (drugs, diseases, regulatory, abbreviations) remain
curated here — NCIt does not model them reliably.

IMPORTANT: Do NOT let an LLM populate this table.  Domain experts must curate
every entry.  An LLM may *suggest* additions, but only a verified clinical
vocabulary (or your internal dictionary) is the authoritative source.

In regulated environments precision matters — a wrong synonym causes false
positives that waste reviewer time and erode trust.
"""

from __future__ import annotations

